import type { ApiModel, Endpoint } from '../model/index.js';
import { BaseExporter } from './exporter.js';
import type { ExportFormat, ExportOptions } from './exporter.js';
import { PlaywrightActionWriter } from './playwright-action-writer.js';
import type { PlaywrightMethod } from './playwright-action-writer.js';
import { PlaywrightRuntime } from './playwright-runtime.js';
import { TypeScriptExporter } from './typescript-exporter.js';

export interface PlaywrightExporterDeps {
  actions?: PlaywrightActionWriter;
}

export class PlaywrightExporter extends BaseExporter {
  static readonly LOGIN_ROLE = 'login';

  readonly format: ExportFormat = 'playwright';
  readonly extension = 'pw.mjs';
  readonly mimeType = 'text/javascript';
  readonly description = 'Playwright browser client that drives the page so the page sends each request';

  readonly #actions: PlaywrightActionWriter;

  static create(): PlaywrightExporter {
    return new PlaywrightExporter({ actions: PlaywrightActionWriter.create() });
  }

  constructor(deps: PlaywrightExporterDeps = {}) {
    super();
    this.#actions = deps.actions ?? PlaywrightActionWriter.create();
  }

  static clientName(model: ApiModel): string {
    return TypeScriptExporter.clientName(model);
  }

  protected render(model: ApiModel, endpoints: Endpoint[], options: ExportOptions): string {
    const clientName = PlaywrightExporter.clientName(model);
    const taken = new Set<string>(PlaywrightActionWriter.RESERVED);
    const loginEndpoint = endpoints.find((endpoint) => endpoint.role === PlaywrightExporter.LOGIN_ROLE);
    const methods: PlaywrightMethod[] = [];
    let loginName: string | undefined;
    for (const endpoint of endpoints) {
      const method = this.#actions.method(endpoint, taken, model.primaryOrigin);
      methods.push(method);
      if (endpoint === loginEndpoint) loginName = method.name;
    }
    const loginMethod = loginName === undefined ? '' : `\n\n  async login(vars = {}) {\n    return this.${loginName}(vars);\n  }`;
    const classBody = methods.map((method) => method.code).join('\n\n');
    const origin = options.baseUrl ?? model.primaryOrigin;
    const header = PlaywrightExporter.#header(clientName, this.filename(model), loginName !== undefined);
    const klass = `${PlaywrightRuntime.classHead(clientName)}${loginMethod}${classBody === '' ? '' : `\n\n${classBody}`}\n}`;
    return `${[header, PlaywrightRuntime.prelude(origin), klass, PlaywrightRuntime.main(clientName, methods.map((method) => method.name), loginName !== undefined)].join('\n\n')}\n`;
  }

  static #header(clientName: string, file: string, hasLogin: boolean): string {
    const lines = [
      `${clientName} - a Playwright browser client generated by appii.`,
      '',
      "Each method drives the real page (navigate, fill, click) so the page's own",
      'code sends the request. The request carries the live browser session, so',
      'cookies, CSRF tokens and any header the page computes stay authentic.',
      'Responses are awaited with waitForResponse; every wait is deterministic.',
      '',
      'Install:  npm install playwright',
      `List:     node ${file} --list`,
      `Run one:  node ${file} <endpoint> [name=value ...]`,
      'Env:      APPII_BASE_URL overrides the base URL; APPII_HEADFUL=1 shows the window.',
      'Secrets come from name=value arguments or APPII_<NAME> env vars; none are baked in.',
    ];
    if (hasLogin) lines.push('Log in first: pass APPII_LOGIN=1 (or vars.__login=1) to run login() before the endpoint.');
    return `/*\n${lines.map((line) => (line === '' ? ' *' : ` * ${line}`)).join('\n')}\n */`;
  }
}
