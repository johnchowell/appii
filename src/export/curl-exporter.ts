import type { ApiModel, Endpoint } from '../model/index.js';
import { Curl, EndpointIndex, Meta, SampleText, Samples, ShellScript, Text } from '../shared/index.js';
import { BaseExporter } from './exporter.js';
import type { ExportFormat, ExportOptions } from './exporter.js';
import { Helpers } from './helpers.js';

export class CurlExporter extends BaseExporter {
  static readonly BASE_VARIABLE = 'BASE_URL';
  static readonly COOKIE_VARIABLE = 'COOKIE';
  static readonly COOKIE_HELPER = 'appii_cookie';
  static readonly FUNCTION_SUFFIX = 'Endpoint';
  static readonly REDACTED_VALUE: RegExp = /^(?:<redacted>|[\s\S]{4}\.\.\.)$/;
  static readonly RESERVED_FUNCTIONS: ReadonlySet<string> = new Set([
    'list', 'usage', 'main', 'help', 'appii_cookie', 'curl', 'cat', 'printf', 'bash', 'sh', 'alias', 'bg', 'bind', 'break', 'builtin',
    'caller', 'case', 'cd', 'command', 'compgen', 'complete', 'compopt', 'continue', 'coproc', 'declare', 'dirs', 'disown', 'do',
    'done', 'echo', 'elif', 'else', 'enable', 'esac', 'eval', 'exec', 'exit', 'export', 'false', 'fc', 'fg', 'fi', 'for', 'function',
    'getopts', 'hash', 'history', 'if', 'in', 'jobs', 'kill', 'let', 'local', 'logout', 'mapfile', 'popd', 'pushd', 'pwd', 'read',
    'readarray', 'readonly', 'return', 'select', 'set', 'shift', 'shopt', 'source', 'suspend', 'test', 'then', 'time', 'times', 'trap',
    'true', 'type', 'typeset', 'ulimit', 'umask', 'unalias', 'unset', 'until', 'wait', 'while',
  ]);

  readonly format: ExportFormat = 'curl';
  readonly extension = 'sh';
  readonly mimeType = 'application/x-sh';
  readonly description = 'Bash script with one curl function per endpoint, a list command and a dispatcher';

  functionNames(endpoints: readonly Endpoint[]): Map<Endpoint, string> {
    const taken = new Set<string>(CurlExporter.RESERVED_FUNCTIONS);
    const out = new Map<Endpoint, string>();
    for (const endpoint of endpoints) {
      let base = endpoint.name.replace(/[^A-Za-z0-9_]/g, '_');
      if (base === '' || /^[0-9]/.test(base)) base = `endpoint_${base}`;
      if (CurlExporter.RESERVED_FUNCTIONS.has(base)) base += CurlExporter.FUNCTION_SUFFIX;
      out.set(endpoint, Text.uniqueName(base, taken, '_'));
    }
    return out;
  }

  originVariables(model: ApiModel, endpoints: readonly Endpoint[]): Map<string, string> {
    const out = new Map<string, string>();
    const taken = new Set<string>([CurlExporter.BASE_VARIABLE, CurlExporter.COOKIE_VARIABLE]);
    Helpers.origins(model, endpoints).forEach((origin, i) => {
      if (i === 0) {
        out.set(origin, CurlExporter.BASE_VARIABLE);
        return;
      }
      let host = origin;
      try {
        host = new URL(origin).host;
      } catch {
        host = origin;
      }
      out.set(origin, Text.uniqueName(`${CurlExporter.BASE_VARIABLE}_${Text.snakeCase(host).toUpperCase() || 'ORIGIN'}`, taken, '_'));
    });
    return out;
  }

  defaultCookie(model: ApiModel, endpoints: readonly Endpoint[]): string {
    const ids = new Set(endpoints.map((endpoint) => endpoint.id));
    const used = new Set(endpoints.flatMap((endpoint) => endpoint.auth.cookies));
    const pairs = new Map<string, string>();
    for (const cookie of model.cookies) {
      if (pairs.has(cookie.name) || cookie.name === '') continue;
      if (!used.has(cookie.name) && !cookie.usedBy.some((id) => ids.has(id))) continue;
      if (CurlExporter.REDACTED_VALUE.test(cookie.valueExample) || Samples.isRedacted(cookie.valueExample)) continue;
      pairs.set(cookie.name, cookie.valueExample);
    }
    return [...pairs].map(([name, value]) => `${name}=${value}`).join('; ');
  }

  script(model: ApiModel, endpoints: Endpoint[], options: ExportOptions = {}): string {
    const opts = Helpers.normalizeOptions(options);
    const index = EndpointIndex.of(model);
    const origins = this.originVariables(model, endpoints);
    const names = this.functionNames(endpoints);
    const originNames = new Set(origins.values());
    const functions: string[] = [];
    const placeholders = new Set<string>();
    for (const endpoint of endpoints) {
      const variable = origins.get(endpoint.origin) ?? CurlExporter.BASE_VARIABLE;
      const sample = Samples.requestSample(endpoint, { baseUrl: SampleText.placeholder(variable) });
      const used = Curl.placeholderNames(sample).filter((name) => !originNames.has(name));
      used.forEach((name) => placeholders.add(name));
      functions.push(this.#function(endpoint, names.get(endpoint) ?? endpoint.name, sample, used));
    }
    const lines: string[] = [
      '#!/usr/bin/env bash',
      `# ${CurlExporter.#comment(Helpers.title(model, opts))}: ${Text.plural(endpoints.length, 'endpoint')}, generated by ${Meta.APP_NAME} ${Meta.appVersion()}.`,
      '# Usage: bash endpoints.sh [ENDPOINT [CURL_ARGS...]]  (run without arguments to list the endpoints)',
      'set -euo pipefail',
      '',
    ];
    for (const [origin, variable] of origins) {
      lines.push(ShellScript.ascii(`DEFAULT_${variable}=${Text.shellQuote(Helpers.originBase(model, origin, opts))}`));
      lines.push(`${variable}="\${${variable}:-$DEFAULT_${variable}}"`);
    }
    if (origins.size === 0) lines.push(`${CurlExporter.BASE_VARIABLE}="\${${CurlExporter.BASE_VARIABLE}:-}"`);
    lines.push(ShellScript.ascii(`DEFAULT_${CurlExporter.COOKIE_VARIABLE}=${Text.shellQuote(this.defaultCookie(model, endpoints))}`));
    lines.push(`${CurlExporter.COOKIE_VARIABLE}="\${${CurlExporter.COOKIE_VARIABLE}-$DEFAULT_${CurlExporter.COOKIE_VARIABLE}}"`);
    for (const name of [...placeholders].sort()) lines.push(`: "\${${name}:=}"`);
    lines.push('', ...CurlExporter.#cookieHelper(), '');
    for (const fn of functions) lines.push(fn, '');
    lines.push(...this.#list(model, endpoints, index, names), '');
    lines.push(...CurlExporter.#usage(), '');
    lines.push(...this.#main(endpoints, index, names), '');
    lines.push('if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then', '  main "$@"', 'fi');
    return lines.join('\n') + '\n';
  }

  protected render(model: ApiModel, endpoints: Endpoint[], options: ExportOptions): string {
    return this.script(model, endpoints, options);
  }

  protected override filename(_model: ApiModel): string {
    return 'endpoints.sh';
  }

  #function(endpoint: Endpoint, name: string, sample: Samples.RequestSample, placeholders: readonly string[]): string {
    const lines = [`${name}() {`];
    const linked = new Set<string>();
    for (const token of endpoint.auth.csrf) {
      if (token.source !== 'cookie' || !token.sourceName) continue;
      const variable = Curl.variableName(SampleText.placeholderName(token.sourceName));
      if (!placeholders.includes(variable) || linked.has(variable)) continue;
      linked.add(variable);
      lines.push(`  local ${variable}="\${${variable}:-$(${CurlExporter.COOKIE_HELPER} ${Text.shellQuote(token.sourceName)})}"`);
    }
    const command = Curl.curlCommand(sample, { variables: 'shell', cookie: SampleText.placeholder(CurlExporter.COOKIE_VARIABLE), extraArgs: ['"$@"'] });
    lines.push(ShellScript.indent(command, 2), '}');
    return ShellScript.ascii(lines.join('\n'));
  }

  #list(model: ApiModel, endpoints: readonly Endpoint[], index: EndpointIndex, names: ReadonlyMap<Endpoint, string>): string[] {
    const rows = endpoints.map((endpoint) => [
      String(index.numberOf(endpoint)),
      endpoint.method,
      Text.toAscii(endpoint.origin === model.primaryOrigin ? endpoint.path : endpoint.origin + endpoint.path, 'replace'),
      names.get(endpoint) ?? endpoint.name,
    ]);
    const header = ['#', 'METHOD', 'PATH', 'FUNCTION'];
    const widths = header.map((title, i) => Math.max(title.length, ...rows.map((row) => (row[i] ?? '').length)));
    const format = (row: string[]): string =>
      row
        .map((cell, i) => (i === 0 ? cell.padStart(widths[0] ?? 0) : i === row.length - 1 ? cell : cell.padEnd(widths[i] ?? 0)))
        .join('  ')
        .trimEnd();
    return ['list() {', "  cat <<'APPII_LIST'", format(header), ...rows.map(format), 'APPII_LIST', '}'];
  }

  #main(endpoints: readonly Endpoint[], index: EndpointIndex, names: ReadonlyMap<Endpoint, string>): string[] {
    const lines = [
      'main() {',
      '  if [[ $# -eq 0 ]]; then',
      '    list',
      '    return 0',
      '  fi',
      '  local command="$1"',
      '  shift',
      '  case "$command" in',
      '    -h|--help|help) usage ;;',
      '    -l|--list|list) list ;;',
    ];
    for (const endpoint of endpoints) {
      const name = names.get(endpoint) ?? endpoint.name;
      lines.push(`    ${name}|${index.numberOf(endpoint)}) ${name} "$@" ;;`);
    }
    lines.push(
      "    *)",
      "      printf 'Unknown endpoint: %s\\n\\n' \"$command\" >&2",
      '      list >&2',
      '      return 2',
      '      ;;',
      '  esac',
      '}',
    );
    return lines;
  }

  static #cookieHelper(): string[] {
    return [
      `${CurlExporter.COOKIE_HELPER}() {`,
      '  local wanted="$1" pair name',
      '  local -a pairs=()',
      `  IFS=';' read -r -a pairs <<< "$${CurlExporter.COOKIE_VARIABLE}" || true`,
      '  for pair in "${pairs[@]+"${pairs[@]}"}"; do',
      '    pair="${pair#"${pair%%[![:space:]]*}"}"',
      '    name="${pair%%=*}"',
      '    if [[ "$pair" == *=* && "$name" == "$wanted" ]]; then',
      "      printf '%s' \"${pair#*=}\"",
      '      return 0',
      '    fi',
      '  done',
      '  return 0',
      '}',
    ];
  }

  static #usage(): string[] {
    return [
      'usage() {',
      "  cat <<'APPII_USAGE'",
      'Usage: bash endpoints.sh [ENDPOINT [CURL_ARGS...]]',
      '',
      'ENDPOINT is a function name or an endpoint number from the list; extra',
      'arguments are passed to curl (for example -i or -v).',
      '',
      'Environment:',
      '  BASE_URL   base URL of the API (default: the captured origin)',
      '  COOKIE     Cookie header value sent with every request',
      '  Placeholders such as CSRF tokens are read from upper-case variables.',
      '',
      'The script can also be sourced to call the endpoint functions directly.',
      'APPII_USAGE',
      '}',
    ];
  }

  static #comment(text: string): string {
    return Text.toAscii(text, 'replace').replace(/[\r\n]+/g, ' ');
  }
}
