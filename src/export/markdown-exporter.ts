import type { ApiModel, BodyShape, Endpoint, ParamInfo } from '../model/index.js';
import { Credentials, Curl, EndpointIndex, Http, Json, Meta, RequestBodies, Schema, Text } from '../shared/index.js';
import { BaseExporter } from './exporter.js';
import type { ExportFormat, ExportOptions } from './exporter.js';
import { Helpers } from './helpers.js';
import { LoginGuide } from './login-guide.js';
import { MarkdownWriter } from './markdown-writer.js';
import { SchemaFieldList } from './schema-field-list.js';
import { SessionGuide } from './session-guide.js';

export interface MarkdownExporterDeps {
  writer?: MarkdownWriter;
  fields?: SchemaFieldList;
}

export class MarkdownExporter extends BaseExporter {
  readonly format: ExportFormat = 'markdown';
  readonly extension = 'md';
  readonly mimeType = 'text/markdown';
  readonly description = 'Markdown documentation with endpoint tables, details and cookies';
  static readonly UNSAFE_PATTERN_NOTE = `A pattern marked (${Schema.UNSAFE_PATTERN}) can take a very long time to check. ${Helpers.UNSAFE_PATTERN_CLIENT}`;
  static readonly FORM_PAGES = 3;
  static readonly SCHEMA_OPEN = '<details><summary>JSON Schema</summary>';
  static readonly DETAILS_CLOSE = '</details>';

  readonly #md: MarkdownWriter;
  readonly #fields: SchemaFieldList;

  static create(): MarkdownExporter {
    return new MarkdownExporter({ writer: new MarkdownWriter(), fields: new SchemaFieldList() });
  }

  constructor(deps: MarkdownExporterDeps = {}) {
    super();
    this.#md = deps.writer ?? new MarkdownWriter();
    this.#fields = deps.fields ?? new SchemaFieldList();
  }

  document(model: ApiModel, endpoints: Endpoint[], options: ExportOptions = {}): string {
    const opts = Helpers.normalizeOptions(options);
    const index = EndpointIndex.of(model);
    const guide = new LoginGuide(model, endpoints);
    const session = SessionGuide.create(model);
    const sections = [
      this.#md.heading(1, Helpers.title(model, opts)),
      this.#summary(model, endpoints, index, guide),
      this.#md.heading(2, 'Endpoints'),
      ...this.#tables(model, endpoints, index),
      this.#md.heading(2, 'Endpoint details'),
      ...endpoints.map((endpoint) => this.#detail(model, endpoint, index, opts, guide, session)),
      this.#md.heading(2, 'Cookies'),
      this.#cookies(model),
      this.#md.heading(2, 'Forms'),
      this.#forms(model, opts),
    ];
    if (model.websockets.length > 0) sections.push(this.#md.heading(2, 'WebSockets'), this.#websockets(model));
    return sections.join('\n\n') + '\n';
  }

  protected render(model: ApiModel, endpoints: Endpoint[], options: ExportOptions): string {
    return this.document(model, endpoints, options);
  }

  protected override filename(_model: ApiModel): string {
    return 'API.md';
  }

  #summary(model: ApiModel, endpoints: readonly Endpoint[], index: EndpointIndex, guide: LoginGuide): string {
    const md = this.#md;
    const source = model.source;
    const span = source.capturedFrom && source.capturedTo ? ` between ${source.capturedFrom} and ${source.capturedTo}` : '';
    const intro = `${md.text(`Generated by ${Meta.APP_NAME} ${Meta.appVersion()} at ${model.generatedAt} from ${Text.plural(source.exchanges, 'captured exchange')}${span}.`)} ${md.text(MarkdownWriter.ESCAPE_LEGEND)}`;
    const kinds = new Map<string, number>();
    for (const endpoint of endpoints) kinds.set(endpoint.kind, (kinds.get(endpoint.kind) ?? 0) + 1);
    const rows: string[][] = [
      ['Origins', model.origins.map((origin) => md.code(origin, true)).join(', ')],
      ['Start URL', source.startUrl ? md.code(source.startUrl, true) : ''],
      ['Endpoints', md.text(`${endpoints.length}${endpoints.length === model.endpoints.length ? '' : ` of ${model.endpoints.length}`}${kinds.size > 0 ? ` (${[...kinds].map(([kind, count]) => `${kind} ${count}`).join(', ')})` : ''}`)],
      ['Exchanges', String(source.exchanges)],
      ['Cookies', String(model.cookies.length)],
      ['Forms', md.text(Helpers.formTotals(model.forms))],
      ['WebSockets', String(model.websockets.length)],
    ];
    const link = (endpoint: Endpoint): string => `[${md.text(`#${index.numberOf(endpoint)} ${endpoint.method} ${endpoint.path}`)}](#${MarkdownExporter.anchor(index.numberOf(endpoint), endpoint)})`;
    const code = (value: string): string => md.code(value);
    for (const endpoint of [...guide.logins(endpoints), ...guide.logouts(endpoints)]) rows.push([LoginGuide.roleLabel(endpoint), `${link(endpoint)}: ${guide.summary(endpoint, code) ?? ''}`]);
    for (const capture of source.captures ?? []) {
      rows.push(['Capture', md.text(`${capture.file ?? capture.startUrl ?? ''}: ${Text.plural(capture.exchanges, 'exchange')} between ${capture.capturedFrom} and ${capture.capturedTo}${capture.file !== undefined && capture.startUrl !== undefined ? ` from ${capture.startUrl}` : ''}`)]);
    }
    return `${intro}\n\n${md.table(['Item', 'Value'], rows)}`;
  }

  #tables(model: ApiModel, endpoints: readonly Endpoint[], index: EndpointIndex): string[] {
    const md = this.#md;
    const origins = Helpers.origins(model, endpoints);
    if (origins.length === 0) return ['No endpoints.'];
    return origins.map((origin) => {
      const rows = endpoints
        .filter((endpoint) => endpoint.origin === origin)
        .map((endpoint) => [
          String(index.numberOf(endpoint)),
          endpoint.method,
          md.code(endpoint.path, true),
          `[${md.text(endpoint.name)}](#${MarkdownExporter.anchor(index.numberOf(endpoint), endpoint)})`,
          md.text(endpoint.kind),
          EndpointIndex.statuses(endpoint).join(', '),
          this.#auth(model, endpoint),
          String(endpoint.count),
        ]);
      return `${md.heading(3, origin)}\n\n${md.table(['#', 'Method', 'Path', 'Name', 'Kind', 'Statuses', 'Auth', 'Hits'], rows, ['right', 'left', 'left', 'left', 'left', 'left', 'left', 'right'])}`;
    });
  }

  static anchor(number: number, endpoint: Endpoint): string {
    return `${number}-${Text.kebabCase(endpoint.name) || 'endpoint'}`;
  }

  #auth(model: ApiModel, endpoint: Endpoint): string {
    const parts: string[] = endpoint.role === undefined ? [] : [endpoint.role];
    const credentials = Credentials.describe(endpoint, Credentials.roles(model));
    if (credentials !== '') parts.push(credentials);
    if (endpoint.auth.csrf.length > 0) parts.push('csrf');
    return this.#md.text(parts.join('; '));
  }

  #detail(model: ApiModel, endpoint: Endpoint, index: EndpointIndex, options: ExportOptions, guide: LoginGuide, session: SessionGuide): string {
    const md = this.#md;
    const number = index.numberOf(endpoint);
    const out: string[] = [
      `<a id="${MarkdownExporter.anchor(number, endpoint)}"></a>`,
      md.heading(3, `${number}. ${endpoint.name}: ${endpoint.method} ${endpoint.path}`),
    ];
    const facts: string[] = [
      `- **URL:** ${md.code(Helpers.base(model, endpoint, options) + endpoint.path)}`,
      `- **Kind:** ${md.text(endpoint.kind)}${endpoint.operationName ? ` (operation ${md.code(endpoint.operationName)})` : ''}`,
      `- **Observed:** ${endpoint.count > 0 ? md.text(Text.plural(endpoint.count, 'time')) : 'no; inferred from an HTML form'}`,
    ];
    const role = guide.describe(endpoint, (value) => md.code(value));
    if (role !== undefined) facts.push(`- **Role:** ${role}`);
    const credentials = Credentials.describe(endpoint, guide.roles);
    if (credentials !== '') facts.push(`- **Credentials:** ${md.text(credentials)}`);
    if (credentials !== '' || endpoint.role !== undefined) facts.push(`- **Anonymous:** ${md.text(LoginGuide.anonymousNote(endpoint))}`);
    if (endpoint.auth.seen !== undefined && endpoint.auth.seen.length > 0) facts.push(`- **Seen:** ${md.text(endpoint.auth.seen.join(', '))}`);
    const hint = guide.hint(endpoint, (login) => `[${md.text(`#${index.numberOf(login)} ${login.name}`)}](#${MarkdownExporter.anchor(index.numberOf(login), login)}) (${md.text(`${login.method} ${login.path}`)})`, (value) => md.text(value));
    if (hint !== undefined) facts.push(`- **Log in:** ${hint}`);
    if (endpoint.auth.cookies.length > 0) facts.push(`- **Cookies sent:** ${endpoint.auth.cookies.map((name) => md.code(name)).join(', ')}`);
    if (endpoint.auth.bearer) facts.push('- **Bearer:** Authorization: Bearer token');
    for (const token of endpoint.auth.csrf) {
      const source = Helpers.tokenSource(token, { text: (value) => md.text(value), code: (value) => md.code(value), url: (value) => md.code(Helpers.mapUrl(model, value, options)) });
      const bound = SessionGuide.bound(token, (value) => md.code(value));
      facts.push(`- **CSRF:** ${md.code(token.name)} in the ${md.text(token.location)}, from ${source}${bound === '' ? '' : `, ${bound}`}`);
    }
    const form = Helpers.formSource(endpoint, { text: (value) => md.text(value), code: (value) => md.code(value), url: (value) => md.code(Helpers.mapUrl(model, value, options)) });
    if (form !== undefined) facts.push(`- **Form:** ${form}`);
    out.push(facts.join('\n'));
    const params = [...endpoint.pathParams, ...endpoint.queryParams, ...endpoint.headerParams];
    if (params.length > 0) out.push('**Parameters**', this.#params(params));
    for (const shape of RequestBodies.shapes(endpoint)) out.push(`**Request body** (${md.code(Helpers.bodyLabel(shape))})`, ...this.#body(shape));
    if (endpoint.responses.length > 0) {
      out.push(
        '**Responses**',
        md.table(
          ['Status', 'Count', 'Content', 'Headers'],
          endpoint.responses.map((response) => [
            md.text(`${response.status} ${Http.reasonPhrase(response.status)}`),
            String(response.count),
            response.body && response.body.kind !== 'empty' ? md.code(Helpers.bodyLabel(response.body), true) : '',
            response.headers.map((name) => md.code(name, true)).join(', '),
          ]),
        ),
      );
      for (const response of endpoint.responses) {
        const fields = this.#fields.rows(response.body?.schema);
        if (fields.length === 0 || response.body?.kind !== 'json') continue;
        out.push(`*Response ${response.status} fields*`, this.#fieldTable(fields));
      }
    }
    if (MarkdownExporter.#unsafePatterns(endpoint)) out.push(md.text(MarkdownExporter.UNSAFE_PATTERN_NOTE));
    out.push('**Example request**', ...this.#example(model, endpoint, options));
    for (const variant of RequestBodies.variants(endpoint)) out.push(`**Example request** (${md.code(variant.mediaType)})`, ...this.#example(model, variant.endpoint, options));
    const steps = session.steps(endpoint, { code: (value) => md.code(value), url: (value) => md.code(Helpers.mapUrl(model, value, options)) });
    if (steps !== undefined) {
      out.push(`**${SessionGuide.TITLE}**`, [...steps.steps, md.text(steps.lead)].join(' '), md.block(steps.commands.join('\n'), 'bash'));
      if (steps.notes.length > 0) out.push(steps.notes.join(' '));
    }
    return out.join('\n\n');
  }

  #example(model: ApiModel, endpoint: Endpoint, options: ExportOptions): string[] {
    const md = this.#md;
    const sample = Helpers.sample(model, endpoint, options);
    const out = [md.block(Curl.curlCommand(sample, { variables: 'shell', explain: true }), 'bash')];
    const variables = Curl.placeholderNames(sample);
    if (variables.length > 0) out.push(`${md.text(Curl.VARIABLES_LABEL)} ${variables.map((name) => md.code(name)).join(' ')}`);
    return out;
  }

  static #unsafePatterns(endpoint: Endpoint): boolean {
    const schemas = [...endpoint.pathParams, ...endpoint.queryParams, ...endpoint.headerParams].map((param) => param.schema);
    for (const shape of RequestBodies.shapes(endpoint)) if (shape.schema) schemas.push(shape.schema);
    return schemas.some((schema) => Schema.unsafePatterns(schema).length > 0);
  }

  #params(params: readonly ParamInfo[]): string {
    const md = this.#md;
    return md.table(
      ['Name', 'In', 'Required', 'Type', 'Constraints', 'Examples'],
      params.map((param) => [
        md.code(param.name, true),
        param.in,
        param.required ? 'yes' : 'no',
        md.text(Schema.typeLabel(param.schema)),
        md.text(Schema.constraintSummary(param.schema, Schema.FULL_SUMMARY).join('; ')),
        param.examples.map((example) => md.code(example, true)).join(', '),
      ]),
    );
  }

  #body(shape: BodyShape): string[] {
    const fields = this.#fields.rows(shape.schema);
    const out: string[] = [];
    if (fields.length > 0) out.push(this.#fieldTable(fields));
    if (shape.schema) out.push(MarkdownExporter.SCHEMA_OPEN, this.#md.block(Json.asciiJson(shape.schema), 'json'), MarkdownExporter.DETAILS_CLOSE);
    const example = shape.examples[0];
    if (shape.jsonLines === true) out.push(this.#md.block(Helpers.jsonLines(shape.examples), ''));
    else if (example !== undefined) out.push(this.#md.block(typeof example === 'string' ? example : Json.asciiJson(example), typeof example === 'string' ? '' : 'json'));
    return out;
  }

  #fieldTable(fields: ReturnType<SchemaFieldList['rows']>): string {
    const md = this.#md;
    return md.table(
      ['Field', 'Type', 'Required', 'Constraints', 'Label'],
      fields.map((field) => [md.code(field.path, true), md.text(field.type), md.text(SchemaFieldList.requiredText(field)), md.text(field.constraints.join('; ')), md.text(field.description ?? '')]),
    );
  }

  #cookies(model: ApiModel): string {
    const md = this.#md;
    if (model.cookies.length === 0) return 'No cookies were captured.';
    const yes = (flag: boolean): string => (flag ? 'yes' : 'no');
    return md.table(
      ['Name', 'Domain', 'Path', 'Role', 'HttpOnly', 'Secure', 'SameSite', 'Partition', 'Expires', 'Set by', 'Used by', 'Issued by', 'Revoked by'],
      model.cookies.map((cookie) => [
        md.code(cookie.name, true),
        md.code(cookie.domain, true),
        md.code(cookie.path, true),
        md.text(cookie.role),
        yes(cookie.httpOnly),
        yes(cookie.secure),
        md.text(cookie.sameSite ?? ''),
        md.text(cookie.partitionKey ?? ''),
        md.text(cookie.session ? 'session' : (cookie.expires ?? '')),
        md.text(cookie.setBy.join(', ')),
        md.text(cookie.usedBy.join(', ')),
        md.text((cookie.issuedBy ?? []).join(', ')),
        md.text((cookie.revokedBy ?? []).join(', ')),
      ]),
    );
  }

  #forms(model: ApiModel, options: ExportOptions): string {
    const md = this.#md;
    if (model.forms.length === 0) return 'No forms were found.';
    return md.table(
      ['Page', 'Selector', 'Method', 'Action', 'Encoding', 'Fields', 'Token fields', 'Seen'],
      model.forms.map((form) => {
        const pages = Helpers.formPages(form);
        const shown = pages.slice(0, MarkdownExporter.FORM_PAGES).map((page) => md.code(Helpers.mapUrl(model, page, options), true));
        const more = pages.length - shown.length;
        return [
          md.code(Helpers.mapUrl(model, form.pageUrl, options), true),
          md.code(form.selector, true),
          md.text(form.method),
          md.code(Helpers.mapUrl(model, form.action, options), true),
          md.text(form.enctype),
          String(form.fields.length),
          md.text(form.tokenFields.join(', ') || '-'),
          `${md.text(Helpers.formSeen(form))}${pages.length > 1 ? `: ${shown.join(', ')}${more > 0 ? md.text(`, +${more} more`) : ''}` : ''}`,
        ];
      }),
    );
  }

  #websockets(model: ApiModel): string {
    const md = this.#md;
    return md.table(
      ['URL', 'Messages', 'Examples'],
      model.websockets.map((socket) => [md.code(socket.url, true), String(socket.messages), socket.examples.map((example) => md.code(Text.truncate(example, 120), true)).join(' ')]),
    );
  }
}
