import { ENDPOINT_KINDS } from '../model/index.js';
import type { ApiModel, Endpoint, EndpointKind } from '../model/index.js';
import { EndpointIndex, Meta, Text } from '../shared/index.js';
import { BaseExporter } from './exporter.js';
import type { ExportFormat, ExportOptions } from './exporter.js';
import { Helpers } from './helpers.js';
import { LoginGuide } from './login-guide.js';
import { SessionGuide } from './session-guide.js';
import { HtmlChartRenderer } from './html-chart-renderer.js';
import type { ChartDatum } from './html-chart-renderer.js';
import { HtmlEndpointRenderer } from './html-endpoint-renderer.js';
import { HtmlReportAssets } from './html-report-assets.js';

export interface HtmlExporterDeps {
  charts?: HtmlChartRenderer;
  endpoints?: HtmlEndpointRenderer;
}

export class HtmlExporter extends BaseExporter {
  static readonly TOP_ENDPOINTS = 15;
  static readonly KINDS: readonly EndpointKind[] = ENDPOINT_KINDS;

  readonly format: ExportFormat = 'html';
  readonly extension = 'html';
  readonly mimeType = 'text/html';
  readonly description = 'Self-contained HTML report with charts, a searchable endpoint list and details';

  readonly #charts: HtmlChartRenderer;
  readonly #endpoints: HtmlEndpointRenderer;

  static create(): HtmlExporter {
    return new HtmlExporter({ charts: new HtmlChartRenderer(), endpoints: HtmlEndpointRenderer.create() });
  }

  constructor(deps: HtmlExporterDeps = {}) {
    super();
    this.#charts = deps.charts ?? new HtmlChartRenderer();
    this.#endpoints = deps.endpoints ?? new HtmlEndpointRenderer();
  }

  report(model: ApiModel, endpoints: Endpoint[], options: ExportOptions = {}): string {
    const opts = Helpers.normalizeOptions(options);
    const index = EndpointIndex.of(model);
    const esc = HtmlEndpointRenderer.esc;
    const title = Helpers.title(model, opts);
    return [
      '<!doctype html>',
      '<html lang="en">',
      '<head>',
      '<meta charset="utf-8">',
      '<meta name="viewport" content="width=device-width, initial-scale=1">',
      `<meta name="generator" content="${esc(`${Meta.APP_NAME} ${Meta.appVersion()}`)}">`,
      `<title>${esc(title)} - API report</title>`,
      `<style>\n${HtmlReportAssets.CSS}\n</style>`,
      '</head>',
      '<body>',
      this.#header(model, endpoints, title),
      '<div class="wrap">',
      '<nav class="toc"><a href="#overview">Overview</a><a href="#endpoints">Endpoints</a><a href="#cookies">Cookies</a><a href="#forms">Forms</a><a href="#websockets">WebSockets</a></nav>',
      '<main>',
      this.#overview(model, endpoints),
      this.#list(model, endpoints, index, opts),
      this.#cookies(model),
      this.#forms(model, opts),
      this.#websockets(model),
      '</main>',
      `<footer>Generated by ${esc(Meta.APP_NAME)} ${esc(Meta.appVersion())} at ${esc(model.generatedAt)}. Captured values are shown as recorded; secrets were redacted when the model was built.</footer>`,
      '</div>',
      `<script>\n${HtmlReportAssets.SCRIPT}\n</script>`,
      '</body>',
      '</html>',
      '',
    ].join('\n');
  }

  protected render(model: ApiModel, endpoints: Endpoint[], options: ExportOptions): string {
    return this.report(model, endpoints, options);
  }

  protected override filename(_model: ApiModel): string {
    return 'report.html';
  }

  #header(model: ApiModel, endpoints: readonly Endpoint[], title: string): string {
    const esc = HtmlEndpointRenderer.esc;
    const source = model.source;
    const facts: [string, string][] = [['Origins', model.origins.length > 0 ? model.origins.map((origin) => `<code>${esc(origin)}</code>`).join(', ') : 'none']];
    if (source.startUrl) facts.push(['Start URL', `<code>${esc(source.startUrl)}</code>`]);
    if (source.capturedFrom && source.capturedTo) {
      const span = Date.parse(source.capturedTo) - Date.parse(source.capturedFrom);
      facts.push(['Captured', `${esc(source.capturedFrom)} to ${esc(source.capturedTo)}${Number.isFinite(span) && span >= 0 ? ` (${esc(Text.formatDuration(span))})` : ''}`]);
    }
    if (source.file) facts.push(['Source file', `<code>${esc(source.file)}</code>`]);
    for (const capture of source.captures ?? []) {
      facts.push(['Capture', `<code>${esc(capture.file ?? capture.startUrl ?? '')}</code>: ${esc(`${Text.plural(capture.exchanges, 'exchange')}, ${capture.capturedFrom} to ${capture.capturedTo}`)}`]);
    }
    const guide = new LoginGuide(model);
    const index = EndpointIndex.of(model);
    const code = (value: string): string => `<code>${esc(value)}</code>`;
    const link = (endpoint: Endpoint): string => `<a href="#endpoint-${index.numberOf(endpoint)}">#${index.numberOf(endpoint)} ${esc(`${endpoint.method} ${endpoint.path}`)}</a>`;
    for (const login of guide.logins(endpoints)) facts.push(['Login', `${link(login)}: ${guide.describe(login, code) ?? ''}`]);
    for (const logout of guide.logouts(endpoints)) facts.push(['Logout', `${link(logout)}: ${guide.describe(logout, code) ?? ''}`]);
    const stats: [number, string][] = [
      [endpoints.length, endpoints.length === model.endpoints.length ? 'endpoints' : `of ${model.endpoints.length} endpoints`],
      [source.exchanges, 'exchanges'],
      [model.cookies.length, 'cookies'],
      [model.forms.length, 'forms'],
      [model.websockets.length, 'websockets'],
    ];
    return [
      '<header class="top"><div class="wrap">',
      `<h1>${esc(title)}</h1>`,
      `<p class="sub">API report generated at ${esc(model.generatedAt)}</p>`,
      `<dl class="facts">${facts.map(([key, value]) => `<dt>${esc(key)}</dt><dd>${value}</dd>`).join('')}</dl>`,
      `<ul class="stats">${stats.map(([value, label]) => `<li><span class="value">${value}</span><span class="label">${esc(label)}</span></li>`).join('')}</ul>`,
      '</div></header>',
    ].join('');
  }

  #overview(model: ApiModel, endpoints: readonly Endpoint[]): string {
    const hits: ChartDatum[] = [...endpoints]
      .filter((endpoint) => endpoint.count > 0)
      .sort((a, b) => b.count - a.count)
      .slice(0, HtmlExporter.TOP_ENDPOINTS)
      .map((endpoint) => ({ label: `${endpoint.method} ${endpoint.path}`, value: endpoint.count, title: `${endpoint.name}: ${Text.plural(endpoint.count, 'hit')}` }));
    const statuses = new Map<number, number>();
    for (const endpoint of endpoints) for (const response of endpoint.responses) statuses.set(response.status, (statuses.get(response.status) ?? 0) + response.count);
    const statusData: ChartDatum[] = [...statuses]
      .sort((a, b) => a[0] - b[0])
      .map(([status, count]) => ({ label: String(status), value: count, tone: HtmlEndpointRenderer.statusClass(status), title: `${status}: ${Text.plural(count, 'response')}` }));
    const kinds: ChartDatum[] = HtmlExporter.KINDS.map((kind) => ({ label: kind, value: endpoints.filter((endpoint) => endpoint.kind === kind).length })).filter((datum) => datum.value > 0);
    const charts = [
      this.#charts.bars(`Hits per endpoint (top ${HtmlExporter.TOP_ENDPOINTS})`, hits, 'hits'),
      this.#charts.bars('Responses by status code', statusData, 'responses'),
      this.#charts.bars('Endpoints by kind', kinds, 'endpoints'),
    ];
    return `<section id="overview"><h2>Overview</h2><div class="charts">${charts.join('')}</div>${model.endpoints.length === 0 ? '<p class="empty">The model has no endpoints.</p>' : ''}</section>`;
  }

  #list(model: ApiModel, endpoints: readonly Endpoint[], index: EndpointIndex, options: ExportOptions): string {
    const esc = HtmlEndpointRenderer.esc;
    const methods = [...new Set(endpoints.map((endpoint) => endpoint.method.toUpperCase()))].sort();
    const kinds = [...new Set(endpoints.map((endpoint) => endpoint.kind))].sort();
    const filters = [
      '<div class="filters">',
      '<input type="search" id="q" placeholder="Filter by path, name or kind" aria-label="Filter endpoints">',
      `<select id="method" aria-label="Method"><option value="">All methods</option>${methods.map((method) => `<option>${esc(method)}</option>`).join('')}</select>`,
      `<select id="kind" aria-label="Kind"><option value="">All kinds</option>${kinds.map((kind) => `<option>${esc(kind)}</option>`).join('')}</select>`,
      `<span id="count" aria-live="polite">${endpoints.length} of ${endpoints.length} endpoints</span>`,
      '</div>',
    ].join('');
    const guide = new LoginGuide(model);
    const session = SessionGuide.create(model);
    const items = endpoints.map((endpoint) => this.#endpoints.item(endpoint, { model, index, options, guide, session })).join('\n');
    return `<section id="endpoints"><h2>Endpoints</h2>${filters}<ol class="endpoints">\n${items}\n</ol>${endpoints.length === 0 ? '<p class="empty">No endpoints selected.</p>' : ''}</section>`;
  }

  #cookies(model: ApiModel): string {
    const esc = HtmlEndpointRenderer.esc;
    if (model.cookies.length === 0) return '<section id="cookies"><h2>Cookies</h2><p class="empty">No cookies were captured.</p></section>';
    const yes = (flag: boolean): string => (flag ? 'yes' : 'no');
    const rows = model.cookies.map(
      (cookie) =>
        `<tr><td><code>${esc(cookie.name)}</code></td><td><code>${esc(cookie.domain)}</code></td><td><code>${esc(cookie.path)}</code></td><td>${esc(cookie.role)}</td>` +
        `<td>${yes(cookie.httpOnly)}</td><td>${yes(cookie.secure)}</td><td>${esc(cookie.sameSite ?? '-')}</td><td>${esc(cookie.partitionKey ?? '-')}</td><td>${esc(cookie.session ? 'session' : (cookie.expires ?? '-'))}</td>` +
        `<td>${esc(cookie.setBy.join(', ') || '-')}</td><td>${esc(cookie.usedBy.join(', ') || '-')}</td><td>${esc((cookie.issuedBy ?? []).join(', ') || '-')}</td><td>${esc((cookie.revokedBy ?? []).join(', ') || '-')}</td><td><code>${esc(cookie.valueExample)}</code></td></tr>`,
    );
    return [
      '<section id="cookies"><h2>Cookies</h2><div class="scroll"><table>',
      '<thead><tr><th>Name</th><th>Domain</th><th>Path</th><th>Role</th><th>HttpOnly</th><th>Secure</th><th>SameSite</th><th>Partition</th><th>Expires</th><th>Set by</th><th>Used by</th><th>Issued by</th><th>Revoked by</th><th>Value</th></tr></thead>',
      `<tbody>${rows.join('')}</tbody></table></div></section>`,
    ].join('');
  }

  #forms(model: ApiModel, options: ExportOptions): string {
    const esc = HtmlEndpointRenderer.esc;
    if (model.forms.length === 0) return '<section id="forms"><h2>Forms</h2><p class="empty">No forms were found.</p></section>';
    const rows = model.forms.map((form) => {
      const pages = Helpers.formPages(form);
      const list = pages.length > 1 ? `<details><summary>${esc(Helpers.formSeen(form))}</summary>${pages.map((page) => `<code>${esc(Helpers.mapUrl(model, page, options))}</code>`).join('<br>')}</details>` : esc(Helpers.formSeen(form));
      return (
        `<tr><td><code>${esc(Helpers.mapUrl(model, form.pageUrl, options))}</code></td><td><code>${esc(form.selector)}</code></td><td>${esc(form.method)}</td>` +
        `<td><code>${esc(Helpers.mapUrl(model, form.action, options))}</code></td><td>${esc(form.enctype)}</td><td>${form.fields.length}</td><td>${esc(form.tokenFields.join(', ') || '-')}</td><td>${list}</td></tr>`
      );
    });
    return [
      '<section id="forms"><h2>Forms</h2><div class="scroll"><table>',
      '<thead><tr><th>Page</th><th>Selector</th><th>Method</th><th>Action</th><th>Encoding</th><th>Fields</th><th>Token fields</th><th>Seen</th></tr></thead>',
      `<tbody>${rows.join('')}</tbody></table></div></section>`,
    ].join('');
  }

  #websockets(model: ApiModel): string {
    const esc = HtmlEndpointRenderer.esc;
    if (model.websockets.length === 0) return '<section id="websockets"><h2>WebSockets</h2><p class="empty">No WebSocket connections were captured.</p></section>';
    const items = model.websockets.map((socket) => {
      const examples = socket.examples.map((example) => `<pre>\n${esc(Text.truncate(example, HtmlEndpointRenderer.MAX_JSON_CHARS))}</pre>`).join('');
      return `<li><code>${esc(socket.url)}</code> - ${esc(Text.plural(socket.messages, 'message'))}${examples}</li>`;
    });
    return `<section id="websockets"><h2>WebSockets</h2><ul>${items.join('')}</ul></section>`;
  }
}
