import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import { MarkdownExporter, MarkdownWriter } from '../src/export/index.js';
import type { ApiModel } from '../src/model/index.js';
import { Text } from '../src/shared/index.js';
import { ExportModel } from './helpers/export-model.js';
import type { ExportFixture } from './helpers/export-model.js';

function section(markdown: string, heading: string): string {
  const start = markdown.indexOf(heading);
  assert.ok(start >= 0, heading);
  const next = markdown.indexOf('\n### ', start + heading.length);
  const nextTop = markdown.indexOf('\n## ', start + heading.length);
  const ends = [next, nextTop].filter((i) => i >= 0);
  return markdown.slice(start, ends.length > 0 ? Math.min(...ends) : undefined);
}

describe('MarkdownExporter', () => {
  let fixture: ExportFixture;
  let model: ApiModel;
  let markdown: string;
  const exporter = new MarkdownExporter();

  before(async () => {
    fixture = await ExportModel.fixture();
    model = fixture.model;
    markdown = exporter.export(model).content;
  });

  after(async () => {
    await fixture?.site.close();
  });

  test('document structure, filename and summary', () => {
    const result = exporter.export(model);
    assert.equal(result.filename, 'API.md');
    assert.equal(result.format, 'markdown');
    assert.ok(Text.isAscii(markdown));
    assert.ok(markdown.startsWith(`# ${model.name}\n\nGenerated by appii `));
    assert.match(markdown, /\n\| Endpoints \| 14 \(document 6, json 4, graphql 1, form 3\) \|\n/);
    assert.deepEqual(
      [...markdown.matchAll(/^## (.+)$/gm)].map((m) => m[1]),
      ['Endpoints', 'Endpoint details', 'Cookies'],
    );
  });

  test('one endpoint table per origin with numbers, links and auth', () => {
    const table = section(markdown, `### ${model.primaryOrigin}`);
    assert.match(table, /\n\| \\# \| Method \| Path \| Name \| Kind \| Statuses \| Auth \| Hits \|\n\| ---: \| --- \| --- \| --- \| --- \| --- \| --- \| ---: \|\n/);
    assert.match(table, /\n\| 5 \| GET \| `\/api\/items\/\{itemId\}` \| \[getItem\]\(#5-get-item\) \| json \| 200, 404 \| cookie auth, sid \| 4 \|\n/);
    assert.match(table, /\n\| 10 \| POST \| `\/login` \| \[postLogin\]\(#10-post-login\) \| form \| 303 \| cookie sid; csrf \| 1 \|\n/);
    assert.match(table, /\n\| 12 \| GET \| `\/search` \| \[getSearch\]\(#12-get-search\) \| form \| - \| cookie auth, sid \| 0 \|/);
  });

  test('endpoint details: facts, parameters, bodies, responses and a curl example', () => {
    const login = section(markdown, '### 10. postLogin: POST /login');
    assert.ok(markdown.includes('<a id="10-post-login"></a>\n\n### 10. postLogin: POST /login'));
    assert.match(login, /- \*\*CSRF:\*\* `csrf_token` in the body, from hidden-field `csrf_token` on `http:\/\/127\.0\.0\.1:\d+\/login`/);
    assert.match(login, /- \*\*Form:\*\* `form#login` on `http:\/\/127\.0\.0\.1:\d+\/login` \(application\/x-www-form-urlencoded\)/);
    assert.match(login, /\n\| `password` \| string \| yes \| html password; length 8\.\. \| Password \|\n/);
    assert.match(login, /\n\| 303 See Other \| 1 \| - \| `location`, `set-cookie: auth` \|\n/);
    assert.match(login, /\*\*Example request\*\*\n\n```bash\ncurl -sS -X POST 'http:\/\/127\.0\.0\.1:\d+\/login' \\\n {2}-H 'Content-Type: application\/x-www-form-urlencoded' \\\n/);
    const list = section(markdown, '### 3. listItems: GET /api/items');
    assert.match(list, /\n\| `page` \| query \| yes \| integer \| - \| `1`, `2` \|\n/);
    assert.match(list, /\*Response 200 fields\*\n\n\| Field \| Type \| Required \| Constraints \| Label \|\n/);
    assert.match(list, /\n\| `items\[\]\.createdAt` \| string\(date-time\) \| yes \| format date-time \| - \|\n/);
    const create = section(markdown, '### 4. createItem: POST /api/items');
    assert.match(create, /```json\n\{\n {2}"name": "Thing",\n {2}"price": 5\n\}\n```/);
  });

  test('cookies table', () => {
    const cookies = markdown.slice(markdown.indexOf('## Cookies'));
    assert.match(cookies, /\n\| `auth` \| `127\.0\.0\.1` \| `\/` \| auth \| yes \| no \| Lax \| - \| session \| post-login \| get-account, /);
    assert.match(cookies, /\n\| `theme` \| `127\.0\.0\.1` \| `\/` \| preference \| no \| no \| - \| - \| \d{4}-\d{2}-\d{2}T/);
  });

  test('selection, title and baseUrl options', () => {
    const result = exporter.export(model, { endpoints: ['createItem'], title: 'Items *API*', baseUrl: 'https://api.example.com/v2' });
    assert.equal(result.endpointCount, 1);
    assert.ok(result.content.startsWith('# Items \\*API\\*\n'));
    assert.match(result.content, /- \*\*URL:\*\* `https:\/\/api\.example\.com\/v2\/api\/items`/);
    assert.match(result.content, /curl -sS -X POST 'https:\/\/api\.example\.com\/v2\/api\/items'/);
    assert.match(result.content, /\| Endpoints \| 1 of 14 \(json 1\) \|/);
  });

  test('hostile and non-ASCII values are escaped', () => {
    const endpoint = ExportModel.endpoint({
      method: 'GET',
      path: '/a|b/`tick`/<x>',
      id: 'weird',
      name: 'get*Weird*_[x](y)',
      requestBody: { mimeType: 'text/plain', kind: 'text', examples: ['```\nnot a fence end\n````'] },
      responses: [{ status: 200, count: 1, headers: ['x|y'], body: { mimeType: 'application/json', kind: 'json', examples: [] } }],
    });
    const hostile = exporter.export(
      ExportModel.model([endpoint], {
        name: '<script>x</script> | Caf\u00e9',
        cookies: [
          {
            name: 'c|1',
            domain: 'shop.example.com',
            path: '/',
            httpOnly: false,
            secure: false,
            sameSite: null,
            session: true,
            expires: null,
            role: 'unknown',
            setBy: [],
            usedBy: [],
            valueExample: 'v',
          },
        ],
        websockets: [{ url: 'wss://shop.example.com/ws', messages: 1, examples: ['a|b`c'] }],
      }),
    ).content;
    assert.ok(Text.isAscii(hostile));
    assert.ok(hostile.startsWith('# \\<script\\>x\\</script\\> \\| Caf\\u00e9\n'));
    assert.match(hostile, /\| 1 \| GET \| ``\/a\\\|b\/`tick`\/<x>`` \| \[get\\\*Weird\\\*\\_\\\[x\\\]\(y\)\]\(#1-get-weird-x-y\) \|/);
    assert.match(hostile, /\n`````\n```\nnot a fence end\n````\n`````\n/);
    assert.match(hostile, /\| `c\\\|1` \|/);
    assert.match(hostile, /\n## WebSockets\n\n\| URL \| Messages \| Examples \|\n\| --- \| --- \| --- \|\n\| `wss:\/\/shop\.example\.com\/ws` \| 1 \| ``a\\\|b`c`` \|/);
  });
});

describe('MarkdownWriter', () => {
  const md = new MarkdownWriter();

  test('text escapes Markdown syntax and non-ASCII characters', () => {
    assert.equal(md.text('a*b_c [d](e) <f> #g ~h !i &j | k `l` \\m\nn'), 'a\\*b\\_c \\[d\\](e) \\<f\\> \\#g \\~h \\!i \\&j \\| k \\`l\\` \\\\m n');
    assert.equal(md.text('Caf\u00e9'), 'Caf\\u00e9');
  });

  test('code spans pick a safe fence and escape pipes only in tables', () => {
    assert.equal(md.code('plain'), '`plain`');
    assert.equal(md.code('a`b'), '``a`b``');
    assert.equal(md.code('`start'), '`` `start ``');
    assert.equal(md.code('a|b'), '`a|b`');
    assert.equal(md.code('a|b', true), '`a\\|b`');
    assert.equal(md.code('', true), '-');
    assert.equal(md.code('line1\nline2'), '`line1 line2`');
  });

  test('blocks, tables and headings', () => {
    assert.equal(md.block('x ``` y', 'json'), '````json\nx ``` y\n````');
    assert.equal(md.table(['A', 'B'], [['1', ''], ['2', 'z']], ['right']), '| A | B |\n| ---: | --- |\n| 1 | - |\n| 2 | z |');
    assert.equal(md.heading(9, 'Deep #'), '###### Deep \\#');
  });
});

describe('MarkdownExporter request examples agree with the other renderers', () => {
  test('a bearer endpoint uses the access_token placeholder and a cookie-sourced CSRF header uses the cookie placeholder', () => {
    const me = ExportModel.endpoint({
      method: 'POST',
      path: '/api/me',
      headerParams: [
        { name: 'authorization', in: 'header', required: true, schema: { type: 'string' }, examples: ['Bearer <redacted>'] },
        { name: 'x-csrf-token', in: 'header', required: true, schema: { type: 'string' }, examples: ['<redacted>'] },
      ],
      auth: { cookies: ['csrftoken'], headers: ['authorization'], bearer: true, csrf: [{ location: 'header', name: 'x-csrf-token', source: 'cookie', sourceName: 'csrftoken' }] },
    });
    const markdown = new MarkdownExporter().export(ExportModel.model([me])).content;
    assert.ok(markdown.includes(`-H 'authorization: Bearer {{access_token}}'`), markdown);
    assert.ok(markdown.includes(`-H 'x-csrf-token: {{csrftoken}}'`), markdown);
    assert.ok(!markdown.includes('{{authorization}}'));
    assert.ok(!markdown.includes('{{x_csrf_token}}'));
  });
});
